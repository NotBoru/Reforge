use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    En,
    PtBr,
}

impl Lang {
    pub fn toggle(self) -> Self {
        match self {
            Lang::En => Lang::PtBr,
            Lang::PtBr => Lang::En,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "EN",
            Lang::PtBr => "PT",
        }
    }
}

