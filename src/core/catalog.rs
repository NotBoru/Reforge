#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AppCategory {
    All,
    Browsers,
    Communication,
    Development,
    Gaming,
    Media,
    Utilities,
    Productivity,
}

impl AppCategory {
    pub const ALL: &'static [AppCategory] = &[
        AppCategory::All,
        AppCategory::Browsers,
        AppCategory::Communication,
        AppCategory::Development,
        AppCategory::Gaming,
        AppCategory::Media,
        AppCategory::Utilities,
        AppCategory::Productivity,
    ];
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PresetKind {
    Essentials,
    Developer,
    Gaming,
    Creator,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InstallerKind {
    Exe,
    Msi,
}

#[derive(Debug, Clone, Copy)]
pub enum DirectSource {
    /// Official vendor evergreen download endpoint (redirect or direct binary).
    StaticUrl {
        url: &'static str,
        kind: InstallerKind,
        silent_args: &'static [&'static str],
    },
    /// Dynamically resolves latest official GitHub release asset matching patterns.
    GitHubRelease {
        repo: &'static str,
        asset_contains: &'static [&'static str],
        asset_excludes: &'static [&'static str],
        asset_ends_with: &'static str,
        kind: InstallerKind,
        silent_args: &'static [&'static str],
    },
}

#[derive(Debug, Clone, Copy)]
pub struct CatalogApp {
    pub id: &'static str,
    pub name: &'static str,
    pub publisher: &'static str,
    pub desc_en: &'static str,
    pub desc_pt: &'static str,
    pub category: AppCategory,
    pub winget_id: &'static str,
    pub direct: Option<DirectSource>,
    pub detect_keywords: &'static [&'static str],
    pub presets: &'static [PresetKind],
}

pub fn catalog() -> &'static [CatalogApp] {
    &CATALOG
}

pub fn preset_app_ids(preset: PresetKind) -> Vec<&'static str> {
    CATALOG
        .iter()
        .filter(|a| a.presets.contains(&preset))
        .map(|a| a.id)
        .collect()
}

